OUTPUT_PATH = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "data", "knowledge", "complaint_dataset.csv")

def generate_complaint_dataset():
    records = []
    counter = 1
    for fault_name, info in FAULT_COMPLAINTS.items():
        for complaint_text in info["complaints"]:
            records.append({"complaint_id": f"C{counter:03d}", "complaint_text": complaint_text, "fault_name": fault_name, "obd_code": info["obd_code"], "fault_category": info["category"]})
            counter += 1
    df = pd.DataFrame(records)
    os.makedirs(os.path.dirname(OUTPUT_PATH), exist_ok=True)
    df.to_csv(OUTPUT_PATH, index=False, encoding="utf-8")
    return df

if __name__ == "__main__":
    df = generate_complaint_dataset()
    print(f"Dataset generated: {len(df)} rows")
